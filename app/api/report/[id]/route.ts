import { NextResponse } from "next/server";
import { getAnalysis, getAllProjects, getProject } from "@/lib/data";
import { inrLakh } from "@/lib/format";

export async function GET(_: Request, { params }: { params: { id: string } }) {
  const p = getProject(params.id);
  const a = getAnalysis(params.id);
  if (!p || !a) return NextResponse.json({ error: "Not found" }, { status: 404 });

  const peers = a.peers.peerIds
    .map(id => getAllProjects().find(x => x.id === id))
    .filter(Boolean) as any[];

  const payload = {
    generatedAt: new Date().toISOString(),
    project: p,
    analysis: a,
    peers: peers.map(q => ({
      id: q.id, name: q.name, sanctionedAmount: q.sanctionedAmount,
      state: q.state, district: q.district, status: q.status
    })),
    disclaimer:
      "This report is generated by the MPLAD Intelligence & Audit System. Risk signals identified are indicators requiring human verification; they do not constitute a legal determination of fraud, misconduct or wrongdoing. The implementing agency and other stakeholders must be given a reasonable opportunity to explain before any adverse conclusion is drawn."
  };
  return NextResponse.json(payload);
}
